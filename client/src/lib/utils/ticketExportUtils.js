import * as XLSX from 'xlsx';
import axios from '../services/apiInterceptor';
import { API_ENDPOINTS } from '../constants/api';

/**
 * Format milestone/service stage identifier into human-readable label
 */
const formatStage = (stage) => {
  if (!stage) return 'Ticket Raised';
  return stage
    .toLowerCase()
    .split('_')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
};

/**
 * Format ISO date string into readable Date & Time format (IST / local)
 */
const formatDateTime = (dateStr) => {
  if (!dateStr) return 'N/A';
  try {
    const d = new Date(dateStr);
    if (isNaN(d.getTime())) return dateStr;
    return d.toLocaleString('en-IN', {
      day: '2-digit',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      hour12: true
    });
  } catch (e) {
    return dateStr;
  }
};

/**
 * Calculate optimal column widths based on maximum content length
 */
const computeColumnWidths = (rows) => {
  if (!rows || rows.length === 0) return [];
  const colKeys = Object.keys(rows[0]);
  return colKeys.map(key => {
    let maxLen = key.length;
    for (const row of rows) {
      const val = row[key];
      const strVal = val === null || val === undefined ? '' : String(val);
      if (strVal.length > maxLen) {
        maxLen = strVal.length;
      }
    }
    return { wch: Math.min(Math.max(maxLen + 3, 10), 60) };
  });
};

/**
 * Transform ticket record into standard Excel row format
 */
const mapTicketToRow = (ticket, index) => ({
  'S.No': index + 1,
  'Ticket Code': ticket.ticketCode || 'N/A',
  'Status': ticket.status || 'N/A',
  'Current Stage': formatStage(ticket.currentStage),
  'Controller No': ticket.controllerNo || 'N/A',
  'IMEI No': ticket.imei || 'N/A',
  'Motor Type': ticket.motorType || 'N/A',
  'Motor HP': ticket.hp || 'N/A',
  'Fault Type': ticket.faultType || 'N/A',
  'Fault Code': ticket.faultCode || 'N/A',
  'Assigned Service Center': ticket.assignedServiceCenter || 'Unassigned',
  'Technician Name': ticket.technician || 'Not Assigned',
  'Technician Contact No': ticket.technicianContactNo || 'N/A',
  'Farmer Name': ticket.farmerName || 'N/A',
  'Supplier Name': ticket.supplierName || 'N/A',
  'Farmer Phone': ticket.farmerPhone || 'N/A',
  'State': ticket.state || 'N/A',
  'District': ticket.district || 'N/A',
  'Village / Block': [ticket.village, ticket.block].filter(Boolean).join(', ') || 'N/A',
  'Created Date & Time': formatDateTime(ticket.createdAt),
  'Last Updated Date & Time': formatDateTime(ticket.updatedAt),
  'Remarks / Notes': ticket.remarks || 'N/A'
});

/**
 * Build Summary & Stats sheet with title block, KPI overview, and breakdown tables
 */
const buildSummarySheet = (stats, dateStr, user) => {
  const total = stats.total || 0;
  const createdToday = stats.createdToday || 0;
  const open = stats.open || 0;
  const inProgress = stats.inProgress || 0;
  const closed = stats.closed || 0;

  const pct = (val) => (total > 0 ? ((val / total) * 100).toFixed(1) + '%' : '0.0%');

  const summaryAoa = [
    ['MACSOFT TICKETING SYSTEM - DAILY ACTIVITY REPORT'],
    ['========================================================================================'],
    ['Report Date:', dateStr, '', 'Generated At:', new Date().toLocaleString('en-IN')],
    ['Generated By:', user?.name || 'Macsoft User', '', 'User Role:', user?.role || 'Macsoft Team'],
    [''],
    ['1. KEY METRICS OVERVIEW'],
    ['----------------------------------------------------------------------------------------'],
    ['Metric', 'Count', 'Percentage of Total'],
    ['Total Tickets Active / Touched Today', total, '100.0%'],
    ['Tickets Created Today', createdToday, pct(createdToday)],
    ['Open Tickets', open, pct(open)],
    ['In Progress Tickets', inProgress, pct(inProgress)],
    ['Closed Tickets Today', closed, pct(closed)],
    [''],
    ['2. SERVICE CENTER DISTRIBUTION'],
    ['----------------------------------------------------------------------------------------'],
    ['Service Center', 'Center Code', 'Open', 'In Progress', 'Closed', 'Total Tickets']
  ];

  const breakdownEntries = Object.values(stats.serviceCenterBreakdown || {});
  if (breakdownEntries.length > 0) {
    breakdownEntries.forEach(sc => {
      summaryAoa.push([
        sc.name || 'Unassigned',
        sc.code || 'N/A',
        sc.open,
        sc.inProgress,
        sc.closed,
        sc.total
      ]);
    });
  } else {
    summaryAoa.push(['No service center activity recorded for today', '-', 0, 0, 0, 0]);
  }

  const ws = XLSX.utils.aoa_to_sheet(summaryAoa);
  ws['!cols'] = [
    { wch: 38 },
    { wch: 22 },
    { wch: 18 },
    { wch: 20 },
    { wch: 18 },
    { wch: 18 }
  ];

  return ws;
};

/**
 * Fetch today's tickets from backend and export cleanly to Excel (.xlsx)
 * @param {Object} options - { date, user }
 * @returns {Promise<{ success: boolean, count: number, filename: string }>}
 */
export const exportTicketsToExcel = async ({ date, user } = {}) => {
  try {
    const params = {};
    if (date) params.date = date;

    const response = await axios.get(`${API_ENDPOINTS.ticket}/export`, { params });
    const { tickets = [], stats = {}, dateRange } = response.data;

    const now = new Date();
    const formattedDate = date || now.toISOString().split('T')[0];
    const displayDate = now.toLocaleDateString('en-IN', {
      day: '2-digit',
      month: 'short',
      year: 'numeric'
    });

    const wb = XLSX.utils.book_new();

    // 1. Summary & Stats Sheet
    const summaryWs = buildSummarySheet(stats, displayDate, user);
    XLSX.utils.book_append_sheet(wb, summaryWs, 'Summary & Stats');

    // 2. All Today Sheet
    const allRows = tickets.map((t, idx) => mapTicketToRow(t, idx));
    const allWs = XLSX.utils.json_to_sheet(allRows.length > 0 ? allRows : [mapTicketToRow({}, 0)]);
    allWs['!cols'] = computeColumnWidths(allRows);
    XLSX.utils.book_append_sheet(wb, allWs, 'All Today');

    // 3. Open Tickets Sheet
    const openTickets = tickets.filter(t => t.status === 'OPEN');
    const openRows = openTickets.map((t, idx) => mapTicketToRow(t, idx));
    const openWs = XLSX.utils.json_to_sheet(openRows.length > 0 ? openRows : [mapTicketToRow({}, 0)]);
    openWs['!cols'] = computeColumnWidths(openRows);
    XLSX.utils.book_append_sheet(wb, openWs, 'Open');

    // 4. In Progress Sheet
    const inProgressTickets = tickets.filter(t => t.status === 'IN_PROGRESS');
    const inProgressRows = inProgressTickets.map((t, idx) => mapTicketToRow(t, idx));
    const inProgressWs = XLSX.utils.json_to_sheet(inProgressRows.length > 0 ? inProgressRows : [mapTicketToRow({}, 0)]);
    inProgressWs['!cols'] = computeColumnWidths(inProgressRows);
    XLSX.utils.book_append_sheet(wb, inProgressWs, 'In Progress');

    // 5. Closed Sheet
    const closedTickets = tickets.filter(t => t.status === 'CLOSED');
    const closedRows = closedTickets.map((t, idx) => mapTicketToRow(t, idx));
    const closedWs = XLSX.utils.json_to_sheet(closedRows.length > 0 ? closedRows : [mapTicketToRow({}, 0)]);
    closedWs['!cols'] = computeColumnWidths(closedRows);
    XLSX.utils.book_append_sheet(wb, closedWs, 'Closed');

    const filename = `Macsoft_Tickets_Report_${formattedDate}.xlsx`;
    XLSX.writeFile(wb, filename);

    return {
      success: true,
      count: tickets.length,
      filename,
      stats
    };
  } catch (error) {
    console.error('Failed to export tickets to Excel:', error);
    throw error;
  }
};
